#!/usr/bin/env node
/**
 * Contract-First sync (SOA-R01, 06-Implementation-Plan §1.3):
 * đọc OpenAPI spec của soa-market-backend (contracts/openapi/<svc>.yaml) và sinh TypeScript types
 * vào src/api/generated/ bằng openapi-typescript. CẤM gõ tay kiểu dữ liệu API.
 *
 * Nguồn spec (ưu tiên từ trên xuống):
 *   1. Tham số dòng lệnh:   npm run sync-contracts -- <dir | base-url>
 *   2. Biến môi trường:     CONTRACTS_SOURCE=<dir | base-url>
 *   3. Mặc định:            ../SOA-Market-Backend/contracts/openapi (repo backend clone cạnh repo này)
 *
 * base-url (VD: raw GitHub của nhánh main) sẽ được thử lần lượt cho 10 dịch vụ: <base-url>/<svc>.yaml
 */
import { mkdir, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import openapiTS, { astToString } from 'openapi-typescript'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const OUT_DIR = path.join(ROOT, 'src', 'api', 'generated')
const DEFAULT_SOURCE = '../SOA-Market-Backend/contracts/openapi'
const SERVICES = ['svc-idn', 'svc-sel', 'svc-prd', 'svc-ord', 'svc-pay', 'svc-shp', 'svc-rev', 'svc-cpl', 'svc-ntf', 'svc-rpt']
const SPEC_EXT = /\.(ya?ml|json)$/i

const source = process.argv[2] || process.env.CONTRACTS_SOURCE || DEFAULT_SOURCE
const isUrl = /^https?:\/\//i.test(source)

/** @returns {Promise<Array<{ name: string, content: string }>>} */
async function loadFromDirectory(dir) {
  const absDir = path.resolve(ROOT, dir)
  let entries
  try {
    entries = await readdir(absDir)
  } catch {
    throw new Error(`Không tìm thấy thư mục contracts: ${absDir}\nClone soa-market-backend cạnh repo này hoặc truyền CONTRACTS_SOURCE.`)
  }
  const files = entries.filter((f) => SPEC_EXT.test(f)).sort()
  return Promise.all(
    files.map(async (file) => ({
      name: file.replace(SPEC_EXT, ''),
      content: await readFile(path.join(absDir, file), 'utf8'),
    })),
  )
}

/** @returns {Promise<Array<{ name: string, content: string }>>} */
async function loadFromUrl(baseUrl) {
  const base = baseUrl.replace(/\/+$/, '')
  const results = await Promise.all(
    SERVICES.map(async (name) => {
      const res = await fetch(`${base}/${name}.yaml`)
      if (res.status === 404) return null
      if (!res.ok) throw new Error(`Tải ${name}.yaml thất bại: HTTP ${res.status}`)
      return { name, content: await res.text() }
    }),
  )
  return results.filter((r) => r !== null)
}

/** "svc-idn" -> "SvcIdn" */
function toNamespace(name) {
  return name
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('')
}

function header(origin) {
  return [
    '/**',
    ' * AUTO-GENERATED by `npm run sync-contracts` — DO NOT EDIT.',
    ` * Source: ${origin}`,
    ' */',
    '',
  ].join('\n')
}

async function main() {
  const specs = isUrl ? await loadFromUrl(source) : await loadFromDirectory(source)
  // Generated files are committed: never embed a machine-specific absolute path in their header.
  const relative = path.relative(ROOT, path.resolve(ROOT, source))
  const origin = isUrl ? source : path.isAbsolute(relative) ? path.basename(relative) : relative.split(path.sep).join('/')

  await rm(OUT_DIR, { recursive: true, force: true })
  await mkdir(OUT_DIR, { recursive: true })

  const generated = []
  for (const spec of specs) {
    try {
      const ast = await openapiTS(spec.content)
      await writeFile(path.join(OUT_DIR, `${spec.name}.ts`), header(`${origin}/${spec.name}`) + astToString(ast))
      generated.push(spec.name)
      console.log(`  ✓ ${spec.name}`)
    } catch (error) {
      throw new Error(`Spec ${spec.name} không hợp lệ: ${error instanceof Error ? error.message : String(error)}`)
    }
  }

  const index = generated.length
    ? generated.map((name) => `export type * as ${toNamespace(name)} from './${name}'`).join('\n') + '\n'
    : '// Chưa có OpenAPI spec nào trong contracts/openapi của backend.\nexport {}\n'
  await writeFile(path.join(OUT_DIR, 'index.ts'), header(origin) + index)

  if (generated.length === 0) {
    console.warn(`⚠ Không có spec nào trong ${origin} — đã tạo index.ts rỗng.`)
  } else {
    console.log(`Đã sinh ${generated.length} contract vào src/api/generated/`)
  }
}

main().catch((error) => {
  console.error(`✗ sync-contracts: ${error instanceof Error ? error.message : String(error)}`)
  process.exit(1)
})
